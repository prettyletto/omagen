package theme

import (
	"fmt"
	"path/filepath"

	"github.com/prettyletto/omagen/backend/internal/fsutil"
)

// WriteHyprland writes the complete theme-local Lua fragment used by Quattro.
func WriteHyprland(themeDir string, palette Palette, style string) error {
	accent := hyprColor(palette.Accent)
	foreground := hyprColor(palette.Foreground)
	inactive := hyprColor(palette.DarkForeground)
	groupbarActive := hyprRGBA(palette.DarkerBackground, "99")
	groupbarInactive := hyprRGBA(palette.LighterBackground, "88")
	shadow := hyprRGBA(palette.DarkerBackground, "b3")

	active := fmt.Sprintf("%q", accent)
	if style == "split" {
		active = gradientLua(accent, foreground, 90)
	} else if style == "cycle" {
		active = gradientLua(accent, hyprColor(palette.Blue), 135)
	} else if style == "neon" {
		active = gradientLua(accent, hyprColor(palette.Magenta), 45)
	}

	content := fmt.Sprintf("-- Generated by Omagen. Panel style: %s.\n"+
		"-- This file uses the Quattro Hyprland Lua API.\n\n"+
		"local active_border_color = %s\n"+
		"local inactive_border_color = %q\n\n"+
		"hl.config({\n"+
		"  general = {\n"+
		"    col = {\n"+
		"      active_border = active_border_color,\n"+
		"      inactive_border = inactive_border_color,\n"+"    },\n"+
		"    gaps_in = 4,\n"+
		"    gaps_out = 5,\n"+
		"    border_size = 2,\n"+
		"  },\n\n"+
		"  group = {\n"+
		"    col = {\n"+
		"      border_active = %q,\n"+
		"      border_inactive = inactive_border_color,\n"+
		"    },\n"+
		"    groupbar = {\n"+
		"      col = {\n"+
		"        active = %q,\n"+
		"        inactive = %q,\n"+
		"      },\n"+
		"      text_color = %q,\n"+
		"      text_color_inactive = %q,\n"+
		"    },\n"+
		"  },\n\n"+
		"  decoration = {\n"+
		"    rounding = 3,\n"+
		"    rounding_power = 3,\n"+
		"    shadow = {\n"+
		"      enabled = true,\n"+
		"      render_power = 4,\n"+
		"      range = 16,\n"+
		"      color = %q,\n"+
		"    },\n"+
		"  },\n"+
		"})\n",
		style, active, inactive, accent, groupbarActive, groupbarInactive, accent, foreground, shadow)
	return fsutil.AtomicWriteFile(filepath.Join(themeDir, "hyprland.lua"), []byte(content), 0o644)
}

func gradientLua(first, second string, angle int) string {
	return fmt.Sprintf("{ colors = { %q, %q }, angle = %d }", first, second, angle)
}

func hyprColor(hex string) string {
	if len(hex) == 7 {
		return "rgb(" + hex[1:] + ")"
	}
	return "rgb(ffffff)"
}

func hyprRGBA(hex, alpha string) string {
	if len(hex) == 7 {
		return fmt.Sprintf("rgba(%s%s)", hex[1:], alpha)
	}
	return "rgba(ffffff" + alpha + ")"
}
